"""Export Python runtime shapes as JSON Schema and frontend TypeScript types."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))


def ts_type(schema: dict, indent: int = 0) -> str:
    if "anyOf" in schema:
        return " | ".join(ts_type(option, indent) for option in schema["anyOf"])
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    kind = schema["type"]
    if kind == "string":
        return "string"
    if kind == "integer":
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {'type': 'object'}), indent)}>"
    if kind == "object":
        fields = []
        required = set(schema.get("required", []))
        for key, child in schema.get("properties", {}).items():
            fields.append(" " * (indent + 2) + f"{key}{'' if key in required else '?'}: " +
                          ts_type(child, indent + 2) + ";")
        fields.append(" " * (indent + 2) + "[key: string]: unknown;")
        return "{\n" + "\n".join(fields) + "\n" + " " * indent + "}"
    raise ValueError(f"Unsupported schema type: {kind}")


def outputs() -> dict[Path, str]:
    from cmne.contracts import SCHEMAS, json_schema

    schema = json.dumps(json_schema(), ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    types = "// Generated by scripts/export_schemas.py. Do not edit by hand.\n\n"
    types += "\n\n".join(f"export type {name} = {ts_type(shape)};" for name, shape in SCHEMAS.items()) + "\n"
    return {ROOT / "schema" / "cmne.schema.json": schema,
            ROOT / "app" / "src" / "generated" / "contracts.ts": types}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    for path, contents in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != contents:
                raise SystemExit(f"Stale generated contract: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents, encoding="utf-8")
            print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
